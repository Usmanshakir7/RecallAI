def create_pdf(result):
    """Create a formatted PDF report from RecallAI meeting insights."""
    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=0.65 * inch,
        leftMargin=0.65 * inch,
        topMargin=0.65 * inch,
        bottomMargin=0.65 * inch,
        title="RecallAI Meeting Report",
        author="RecallAI",
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "RecallTitle", parent=styles["Title"], fontName="Helvetica-Bold",
        fontSize=23, leading=28, alignment=TA_CENTER,
        textColor=colors.HexColor("#5145A8"), spaceAfter=8,
    )
    subtitle_style = ParagraphStyle(
        "RecallSubtitle", parent=styles["Normal"], fontSize=10,
        alignment=TA_CENTER, textColor=colors.HexColor("#64748B"),
        spaceAfter=18,
    )
    heading_style = ParagraphStyle(
        "RecallHeading", parent=styles["Heading2"], fontName="Helvetica-Bold",
        fontSize=14, leading=18, textColor=colors.HexColor("#5145A8"),
        spaceBefore=12, spaceAfter=7,
    )
    body_style = ParagraphStyle(
        "RecallBody", parent=styles["BodyText"], fontName="Helvetica",
        fontSize=10, leading=15, textColor=colors.HexColor("#1E293B"),
        spaceAfter=7, wordWrap="CJK",
    )

    def escape_pdf_text(value):
        return (html.escape(str(value)).replace("\r\n", "\n")
                .replace("\n", "<br/>"))

    story = [
        Paragraph("RecallAI", title_style),
        Paragraph("Meeting Intelligence Report", subtitle_style),
        HRFlowable(width="100%", thickness=1.2,
                   color=colors.HexColor("#63D9E8"), spaceAfter=14),
    ]

    def add_section(title, value):
        story.append(Paragraph(escape_pdf_text(title), heading_style))
        if value is None or value == "":
            story.append(Paragraph("Not available.", body_style))
            return
        if isinstance(value, (list, tuple)):
            if not value:
                story.append(Paragraph("No items identified.", body_style))
                return
            for item in value:
                if isinstance(item, dict):
                    item = " | ".join(
                        f"{key}: {val}" for key, val in item.items()
                        if val is not None and val != ""
                    ) or "Item"
                story.append(Paragraph("&#8226;&nbsp; " + escape_pdf_text(item), body_style))
        else:
            story.append(Paragraph(escape_pdf_text(value), body_style))

    add_section("Executive Summary", result.get("summary"))
    if result.get("key_points"):
        add_section("Important Points", result["key_points"])
    add_section("Topics Discussed", result.get("topics", []))
    add_section("Decisions Made", result.get("decisions", []))
    add_section("Action Items", result.get("action_items", []))
    add_section("Open Questions", result.get("open_questions", []))
    story.extend([Spacer(1, 18), HRFlowable(width="100%", thickness=0.6,
                  color=colors.HexColor("#CBD5E1")), Spacer(1, 8),
                  Paragraph("Generated by RecallAI", subtitle_style)])
    document.build(story)
    buffer.seek(0)
    return buffer.getvalue()


