def safe_text(value):
    """Escape dynamic text before inserting it into HTML."""
    return html.escape(str(value))


def get_item_details(item):
    """Support both dictionary and plain-text insight items."""
    if isinstance(item, dict):
        text = (
            item.get("task")
            or item.get("title")
            or item.get("text")
            or "Untitled item"
        )
        owner = item.get("owner")
        return str(text), str(owner) if owner else None

    return str(item), None


def render_items(items, empty_message="Nothing to show yet."):
    """Render numbered insight cards."""
    if not items:
        st.markdown(
            f'<div class="empty-state">{safe_text(empty_message)}</div>',
            unsafe_allow_html=True,
        )
        return

    for index, item in enumerate(items, start=1):
        text, owner = get_item_details(item)

        owner_html = ""
        if owner:
            owner_html = (
                f'<div class="item-owner">'
                f'↗ Assigned to: {safe_text(owner)}'
                f'</div>'
            )

        st.markdown(
            f"""
            <div class="insight-item">
                <div class="item-number">ITEM {index:02d}</div>
                <div><strong>{safe_text(text)}</strong></div>
                {owner_html}
            </div>
            """,
            unsafe_allow_html=True,
        )


def render_panel_heading(title, subtitle=None):
    """Render a consistent section heading."""
    subtitle_html = ""

    if subtitle:
        subtitle_html = (
            f'<div class="panel-subtitle">'
            f'{safe_text(subtitle)}</div>'
        )

    st.markdown(
        f"""
        <div class="panel">
            <div class="panel-heading">{safe_text(title)}</div>
            {subtitle_html}
        </div>
        """,
        unsafe_allow_html=True,
    )


